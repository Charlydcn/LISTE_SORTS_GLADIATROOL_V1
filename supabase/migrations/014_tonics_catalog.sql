create policy tonic_comments_authenticated_insert on public.tonic_comments for insert to authenticated with check ((select auth.uid()) is not null);
create policy tonic_comments_authenticated_update on public.tonic_comments for update to authenticated using ((select auth.uid()) is not null) with check ((select auth.uid()) is not null);
create policy tonic_comments_authenticated_delete on public.tonic_comments for delete to authenticated using ((select auth.uid()) is not null);

create view public.public_created_tonics with (security_barrier = true) as
