alter table public.entity_overrides
  drop constraint entity_overrides_entity_type_check,
  add constraint entity_overrides_entity_type_check check (entity_type in ('spell', 'spell_position', 'class_stat', 'tonic')),
  drop constraint entity_overrides_allowed_field,
  add constraint entity_overrides_allowed_field check (
    (entity_type = 'spell' and field_key in (
      'nom', 'pa', 'po', 'porteeModifiable', 'lancerEnLigne', 'ligneDeVue',
      'cc', 'ec', 'relance', 'parTour', 'parCible', 'icone', 'effets.normaux', 'effets.critiques'
    ))
    or (entity_type = 'spell_position' and field_key = 'position')
    or (entity_type = 'class_stat' and field_key in (
      'vie', 'pa', 'pm', 'vitalite', 'sagesse', 'force', 'intelligence', 'chance', 'agilite', 'initiative'
    ))
    or (entity_type = 'tonic' and field_key in ('title', 'effects', 'spellId'))
  );

alter table public.change_history
  drop constraint change_history_entity_type_check,
  add constraint change_history_entity_type_check
    check (entity_type in ('spell', 'spell_position', 'class_stat', 'tonic', 'import'));

create table public.created_tonics (
  id bigint generated by default as identity (start with 1000000) primary key,
  tonic jsonb not null,
  created_at timestamptz not null default now(),
  created_by uuid not null,
  created_by_label text not null
);

create table public.deleted_native_tonics (
  tonic_id bigint primary key,
  deleted_at timestamptz not null default now(),
  deleted_by uuid not null,
  deleted_by_label text not null
);

create table public.tonic_comments (
  id uuid primary key default gen_random_uuid(),
  tonic_id text not null check (length(tonic_id) > 0),
  body text not null check (length(btrim(body)) between 1 and 10000),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  created_by uuid not null,
  created_by_label text not null,
  updated_by uuid not null,
  updated_by_label text not null
);

create index tonic_comments_tonic_created_idx on public.tonic_comments (tonic_id, created_at desc);
alter table public.created_tonics enable row level security;
alter table public.deleted_native_tonics enable row level security;
alter table public.tonic_comments enable row level security;
revoke all on table public.created_tonics, public.deleted_native_tonics, public.tonic_comments from public, anon, authenticated;
grant select, insert, update, delete on table public.tonic_comments to authenticated;

